Step 3: Create Truststore

1. Import root

keytool -importcert \
  -alias amazon-root \
  -file amazon-root.crt \
  -keystore papss_truststore.p12 \
  -storetype PKCS12 \
  -storepass changeit \
  -noprompt
  
