    private void transactionAwaitingStatus(String worldremitaction) {
        log.info("TRANSACTIONSTATUS {} RECEIVED", worldremitaction);
        telemetryClient.trackTrace("TRANSACTIONSTATUS {} " + worldremitaction + " RECEIVED", SeverityLevel.Information);

        wrService.getAwaitingTransactionStatus().enqueue(new Callback<Batch>() {
            @Override
            public void onResponse(Call<Batch> call, Response<Batch> response) {
                Batch batch = response.body();
                batch.getContent().forEach(data
                        -> {
                    Transaction transaction = TransactionDTO.createTransactionFromKafka(data.getTransaction());
                    Optional<Transaction> optionalTransaction = transactionDataRepository.findByWorldRemitId(transaction.getWorldRemitId());
                    //These 3 txns below are being exempted to avoid an infite loop from WR system.
                    //WR team refused to remove them from the status awaiting list thus creatng infinite loop.
                    //The txns are not formated corrected and therefore will never be processed successfully in our system
                    //We are exempting them to avoid unnessary consumsion of resources on our end.
                    String reference = data.getTransaction().getReference();
                    String wrid = String.valueOf(data.getTransaction().getWorldRemitId());
                    if (transaction.getReference().equals("795424990001") || transaction.getReference().equals("796096810001") || transaction.getReference().equals("796098400001")) {
                        log.info("Reference: " + transaction.getReference() + " Already exists in our system");
                        telemetryClient.trackTrace("Reference: " + transaction.getReference() + " Already exists in our system", SeverityLevel.Error);
                    } else {
                        TransactionChangeStatus transactionChangeStatus = new TransactionChangeStatus();
                        transactionChangeStatus.setResponseCode("0033");
                        transactionChangeStatus.setResponseMessage("Success");
                        transactionChangeStatus.setTxnReference(transaction.getWrid());
                        PropertiesMap map = new PropertiesMap();
                        transactionChangeStatus.setResponseCode("0033");
                        map.addProperty("responsecode", "0033");
                        map.addProperty("responsemessage", "Transaction not found");
                        map.addProperty("mycustom1", "Transaction with Reference ID [" + transaction.getWorldRemitId() + "] is  not found ");
                        transactionChangeStatus.setProperties(map);
                        if (!optionalTransaction.isPresent()) {
                            setResponse(transaction, transactionChangeStatus);
                        } else {
                            log.info("Sending To Kafka: " + transaction.getWorldRemitId());
                            telemetryClient.trackTrace("Sending To Kafka: " + transaction.getWorldRemitId(), SeverityLevel.Information);
                            sendTransactionToKafka(optionalTransaction.get(), reference, wrid, transactionChangeStatus);
                        }
                    }

                });
            }

            @Override
            public void onFailure(Call<Batch> call, Throwable throwable) {
                log.info("TRANSACTION STATUS ERROR {}", throwable.fillInStackTrace());
                telemetryClient.trackTrace("TRANSACTION STATUS ERROR " + throwable.getMessage(), SeverityLevel.Error);

                ExceptionTelemetry et = new ExceptionTelemetry(throwable);
                telemetryClient.trackException(et);
            }
        });
    }

