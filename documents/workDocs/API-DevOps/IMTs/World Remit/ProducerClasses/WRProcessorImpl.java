    private void setResponse(Transaction transaction, TransactionChangeStatus transactionChangeStatus) {
        wrService.setTransactionResponse(transaction.getWorldRemitId(), transaction.getWorldRemitId(), transactionChangeStatus).enqueue(new Callback<Void>() {
            @Override
            public void onResponse(Call<Void> call, Response<Void> response) {
                log.info(transaction.getWorldRemitId() + " TRANSACTION RESPONSE {}", response.code());
                telemetryClient.trackTrace(transaction.getWorldRemitId() + " TRANSACTION RESPONSE { " + response.code() + " }", SeverityLevel.Information);
                transaction.setMessage("Transaction: " + transaction.getWorldRemitId() + " In The Transaction Awaiting Status List Does Not Exist In Our Systems");
                transaction.setStatus("FAILED - TRANSACTION NOT FOUND");
                transactionDataRepository.save(transaction);
            }

            @Override
            public void onFailure(Call<Void> call, Throwable throwable) {
                log.info(transaction.getWorldRemitId() + " PUBLISH ERROR {}", throwable.getMessage());
                telemetryClient.trackTrace(transaction.getWorldRemitId() + " PUBLISH ERROR {}" + throwable.getMessage(), SeverityLevel.Error);
                transaction.setMessage("Transaction: " + transaction.getWorldRemitId() + " In The Transaction Awaiting Status List Does Not Exist In Our Systems");
                transaction.setStatus("FAILED - TRANSACTION NOT FOUND");
                transactionDataRepository.save(transaction);

                ExceptionTelemetry et = new ExceptionTelemetry(throwable);
                telemetryClient.trackException(et);
            }
        });
    }

    public void sendTransactionToKafka(Transaction transaction, String reference, String wrid, TransactionChangeStatus transactionChangeStatus) {
        ListenableFuture<SendResult<String, Transaction>> future = kafkaTemplate.send(topic, transaction);
        future.addCallback(
                new ListenableFutureCallback<SendResult<String, Transaction>>() {
            @Override
            public void onSuccess(SendResult<String, Transaction> result) {
                log.info(reference + ": Sending To Kafka Success. Kafka Producer Offset Value: " + result.getRecordMetadata().offset());
                telemetryClient.trackTrace(reference + ": Sending To Kafka Success. Kafka Producer Offset Value: " + result.getRecordMetadata().offset(), SeverityLevel.Information);

                transaction.setStatus("PROCESSING");
                transaction.setMessage("Transaction is being processed. " + "Kafka Producer Offset Value: " + result.getRecordMetadata().offset());
                transactionDataRepository.save(transaction);
                log.info("Locking Transaction " + reference + " on Kafka Success");
                telemetryClient.trackTrace("Locking Transaction " + reference + " on Kafka Success", SeverityLevel.Information);

                lockTransaction(reference, transactionChangeStatus, wrid, transaction);
            }

            @Override
            public void onFailure(Throwable ex) {
                transaction.setStatus("FAILED");
                transaction.setMessage("Transaction not written to kafka " + ex.getMessage());
                transactionDataRepository.save(transaction);
                log.info("Transaction  " + reference + " Not written to kafka. PUBLISH ERROR {}", ex.getMessage());
                telemetryClient.trackTrace("Transaction  " + reference + " Not written to kafka. PUBLISH ERROR {}" + ex.getMessage(), SeverityLevel.Error);

                ExceptionTelemetry et = new ExceptionTelemetry(ex);
                telemetryClient.trackException(et);
            }
        }
        );
        //lock only on receiving ACK

    }

    private void lockTransaction(String reference, TransactionChangeStatus transactionChangeStatus, String wrid, Transaction transaction) {
        PropertiesMap map = new PropertiesMap();
        map.addProperty("responsecode", "1");
        map.addProperty("responsemessage", "Transaction Locked");
        map.addProperty("txnreference", reference);
        map.addProperty("mycustom1", "Lock Transaction");
        transactionChangeStatus.setProperties(map);

        Optional<Transaction> optionalTransactionLock = transactionDataRepository.findByWorldRemitId(reference);
        HashMap<String, Object> lockMap = new HashMap<>();

        //lock transaction once written to kafka
        wrService.setTransactionLocked(wrid, reference, transactionChangeStatus).enqueue(new Callback<Void>() {
            @Override
            public void onResponse(Call<Void> call, Response<Void> response) {
                log.info(reference + " LOCK STATUS: " + response.code() + ". Transaction Change Status: " + transactionChangeStatus + ". Response Body: " + response.toString());
                telemetryClient.trackTrace(reference + " LOCK STATUS: " + response.code() + ". Transaction Change Status: " + transactionChangeStatus + ". Response Body: " + response.toString(), SeverityLevel.Information);

                PropertiesMap locProperties = transactionChangeStatus.getProperties();
                String lockResponse = response.toString();

                if (optionalTransactionLock.isPresent()) {
                    lockMap.put("lockResponseCode", response.code());
                    lockMap.put("locProperties", locProperties);
                    lockMap.put("lockResponse", lockResponse);
                    log.info("lockMap::: " + lockMap);

                    transaction.setLockStatus(lockMap.get("lockResponseCode").toString());
                    transaction.setLockMessage(lockMap.get("locProperties").toString());
                    transaction.setLockResponse(lockMap.get("lockResponse").toString());
                    transactionDataRepository.save(transaction);

                } else {
                    log.info(reference + " Does Not Exist In Transaction Table");
                    telemetryClient.trackTrace(reference + " Does Not Exist In Transaction Table", SeverityLevel.Information);

                }

            }

            @Override
            public void onFailure(Call<Void> call, Throwable throwable) {
                log.info(reference + " LOCK ERROR: " + throwable.getMessage());
                telemetryClient.trackTrace(reference + " LOCK ERROR: " + throwable.getMessage(), SeverityLevel.Error);

                if (optionalTransactionLock.isPresent()) {
                    transaction.setLockStatus("LOCK FAILED");
                    transaction.setLockMessage(throwable.getMessage());
                    transaction.setLockResponse(null);
                    transactionDataRepository.save(transaction);

                } else {
                    log.info(reference + " Does Not Exist In Transaction Table");
                    telemetryClient.trackTrace(reference + " Does Not Exist In Transaction Table", SeverityLevel.Information);

                }

                ExceptionTelemetry et = new ExceptionTelemetry(throwable);
                telemetryClient.trackException(et);
            }
        });
    }

