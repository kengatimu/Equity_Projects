-- V12: Session correlation, actor email, and audit views
-- Equity Bank Group — DR Management Platform
--
-- Goals
-- ─────
-- 1. Add actor_email to audit_log so every row is self-describing (denormalised
--    for immutability — audit records survive user deletion).
-- 2. Add session_id to email_otps so OTP_REQUESTED, OTP_VERIFIED and every
--    subsequent authenticated action all share the same correlation key.
-- 3. Create two operational views for the security/ops team:
--      v_user_activity    — every event joined with the user's display name
--      v_session_summary  — one row per session with full action sequence

-- ─── 1. audit_log: add actor_email ────────────────────────────────────────────
ALTER TABLE audit_log
    ADD COLUMN IF NOT EXISTS actor_email VARCHAR(255);

-- ─── 2. email_otps: add session_id ────────────────────────────────────────────
-- Generated by the application (UUID v7) on every OTP request.
-- The same UUID is later embedded as the JWT `jti` claim so all events
-- in a session are traceable to a single session_id.
ALTER TABLE email_otps
    ADD COLUMN IF NOT EXISTS session_id UUID;

-- ─── 3. Supporting indexes ─────────────────────────────────────────────────────
CREATE INDEX IF NOT EXISTS idx_audit_log_session
    ON audit_log (session_id)
    WHERE session_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_audit_log_actor_email
    ON audit_log (actor_email, "timestamp" DESC)
    WHERE actor_email IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_email_otps_session
    ON email_otps (session_id)
    WHERE session_id IS NOT NULL;

-- ─── 4. View: v_user_activity ─────────────────────────────────────────────────
-- One row per audit event enriched with the actor's display name.
-- Use for per-user activity feeds, security review, and compliance reports.
-- ORDER BY: "timestamp" DESC in your queries for latest-first.
CREATE OR REPLACE VIEW v_user_activity AS
SELECT
    al.id,
    al."timestamp",
    al.session_id,
    al.action,
    al.resource_type,
    al.resource_id,
    al.campaign_id,
    al.actor_id,
    COALESCE(al.actor_email, u.email)        AS actor_email,
    COALESCE(u.display_name, al.actor_email) AS actor_name,
    u.role                                    AS user_role,
    al.actor_role,
    al.actor_ip,
    al.before_state,
    al.after_state
FROM  audit_log al
LEFT JOIN users u ON u.id = al.actor_id;

-- ─── 5. View: v_session_summary ───────────────────────────────────────────────
-- One row per session_id.  Shows the full action sequence from first event
-- (typically OTP_REQUESTED) through logout.  Useful for:
--   • "Who was logged in and what did they do?"
--   • Detecting sessions without logout (potential token theft)
--   • Measuring session duration for capacity/security analytics
CREATE OR REPLACE VIEW v_session_summary AS
SELECT
    al.session_id,
    MAX(COALESCE(al.actor_email, u.email))            AS actor_email,
    MAX(u.display_name)                                AS actor_name,
    MIN(al."timestamp")                                AS session_start,
    MAX(al."timestamp")                                AS session_end,
    ROUND(EXTRACT(EPOCH FROM
        (MAX(al."timestamp") - MIN(al."timestamp"))))::INT
                                                       AS duration_seconds,
    COUNT(*)                                           AS event_count,
    bool_or(al.action = 'OTP_VERIFIED')                AS login_completed,
    bool_or(al.action = 'USER_LOGOUT')                 AS logged_out,
    array_agg(al.action ORDER BY al."timestamp")       AS action_sequence
FROM  audit_log al
LEFT JOIN users u ON u.id = al.actor_id
WHERE al.session_id IS NOT NULL
GROUP BY al.session_id;
