package com.equitybank.drplatform.dto.response;

import com.equitybank.drplatform.entity.ChecklistItemEntity;
import lombok.*;

import java.time.Instant;
import java.time.LocalDateTime;
import java.time.temporal.ChronoUnit;
import java.util.UUID;

@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class ChecklistItemDto {
    private UUID id;
    private UUID campaignApplicationId;
    private String title;
    private String status;
    private String notes;
    private UUID carriedForwardFromId;
    private LocalDateTime carriedForwardAt;
    private long carriedForwardAgeDays;
    private UUID completedById;
    private LocalDateTime completedAt;
    private boolean autoGenerated;
    private int sortOrder;
    private Instant createdAt;
    private Instant updatedAt;

    public static ChecklistItemDto fromEntity(ChecklistItemEntity e) {
        return ChecklistItemDto.builder()
                .id(e.getId())
                .campaignApplicationId(e.getCampaignApplicationId())
                .title(e.getTitle())
                .status(e.getStatus() != null ? e.getStatus().name() : null)
                .notes(e.getNotes())
                .carriedForwardFromId(e.getCarriedForwardFromId())
                .carriedForwardAt(e.getCarriedForwardAt())
                .carriedForwardAgeDays(e.getCarriedForwardAt() != null
                        ? ChronoUnit.DAYS.between(e.getCarriedForwardAt(), LocalDateTime.now()) : 0)
                .completedById(e.getCompletedById())
                .completedAt(e.getCompletedAt())
                .autoGenerated(Boolean.TRUE.equals(e.getIsAutoGenerated()))
                .sortOrder(e.getSortOrder())
                .createdAt(e.getCreatedAt())
                .updatedAt(e.getUpdatedAt())
                .build();
    }
}
