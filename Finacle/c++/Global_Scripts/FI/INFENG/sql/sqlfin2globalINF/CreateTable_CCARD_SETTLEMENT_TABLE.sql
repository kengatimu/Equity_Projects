  TRANSFER_LOCAL_AMOUNT  VARCHAR2(15 BYTE),
  TRANSFER_DESCRIPTOR    VARCHAR2(100 BYTE),
  AMOUNT_SIGN            VARCHAR2(1 BYTE),
  GROUP_IDENTIFIER       VARCHAR2(9 BYTE),
  TRANSFER_TYPE          VARCHAR2(1 BYTE),
