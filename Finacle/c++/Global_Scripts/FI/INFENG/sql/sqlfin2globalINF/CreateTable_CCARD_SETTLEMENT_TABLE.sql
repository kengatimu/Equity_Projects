

CREATE TABLE CUSTOM.CCARD_SETTLEMENT_TABLE
(
  ROW_CODE               VARCHAR2(2 BYTE),
  ROW_NUMBER             VARCHAR2(6 BYTE),
  TRANSFER_NUMBER        VARCHAR2(10 BYTE),
  TRANSFER_CODE          VARCHAR2(8 BYTE),
  DEBIT_ACCOUNT          VARCHAR2(32 BYTE),
  CREDIT_ACCOUNT         VARCHAR2(32 BYTE),
